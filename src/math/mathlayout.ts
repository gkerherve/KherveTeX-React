export type PhRef = mb.Row | mb.Node
export type Op =
  | { k: 't'; dx: number; dy: number; px: number; text: string }
  | { k: 'rule'; dx: number; dy: number; w: number; h: number }
  | { k: 'stroke' | 'fill'; path: Path; width: number }
  | { k: 'ph'; dx: number; dy: number; w: number; h: number; ref: PhRef }
  | { k: 'chip'; dx: number; dy: number; w: number; h: number; text: string; px: number; kind: 'raw' | 'cmd' }

export class Box {
  w: number
  asc: number
  desc: number
  ops: Op[] = []
  kids: [number, number, Box][] = []      // (dx, dy, Box); dy positive = down
  row: mb.Row | null = null
  gaps: number[] = []
  em = 0
  italic = false
  node: mb.Node | null = null
  charlike = false
  inkR: number | null = null

  constructor(w = 0, asc = 0, desc = 0) {
    this.w = w
    this.asc = asc
    this.desc = desc
  }

  add(dx: number, dy: number, box: Box): void {
    this.kids.push([dx, dy, box])
  }
}

// Math style: level 0=display 1=text 2=script 3=scriptscript.
export class St {
  base: number
  level: number
  variant: string | null
  constructor(base: number, level = 0, variant: string | null = null) {
    this.base = base
    this.level = level
    this.variant = variant
  }
  get em(): number { return this.base * [1.0, 1.0, 0.7, 0.5][this.level]! }
  sup(): St { return new St(this.base, this.level < 2 ? 2 : 3, this.variant) }
  frac(): St { return new St(this.base, this.level ? Math.min(this.level + 1, 3) : 1, this.variant) }
  withLevel(lv: number): St { return new St(this.base, lv, this.variant) }
  withVariant(v: string | null): St { return new St(this.base, this.level, v) }
}

const SP: Record<string, number> = {
  'ord op': 3, 'ord bin': 4, 'ord rel': 5,
  'ord inner': 3,
  'op ord': 3, 'op op': 3, 'op rel': 5, 'op inner': 3,
  'bin ord': 4, 'bin op': 4, 'bin open': 4,
  'bin inner': 4,
  'rel ord': 5, 'rel op': 5, 'rel open': 5,
  'rel inner': 5,
  'close op': 3, 'close bin': 4, 'close rel': 5,
  'close inner': 3,
  'punct ord': 3, 'punct op': 3, 'punct rel': 3,
  'punct open': 3, 'punct close': 3, 'punct punct': 3,
  'punct inner': 3,
  'inner ord': 3, 'inner op': 3, 'inner bin': 4,
  'inner rel': 5, 'inner open': 3, 'inner punct': 3,
  'inner inner': 3,
}
const SP_SCRIPT = new Set(['ord op', 'op ord', 'op op', 'close op', 'inner op'])

const ATOM_GLYPH: Record<string, string> = { '-': '−', '*': '∗', "'": '′' }

function leftCls(n: mb.Node): string | null {
  if (n instanceof mb.Space || n instanceof mb.Scripts) return null
  if (n instanceof mb.Delim) return 'open'
  if (n instanceof mb.Placeholder || n instanceof mb.CmdInput || n instanceof mb.Raw) return 'ord'
  return n.cls
}

function rightCls(n: mb.Node): string | null {
  if (n instanceof mb.Space) return null
  if (n instanceof mb.Delim) return 'close'
  if (n instanceof mb.Placeholder || n instanceof mb.CmdInput || n instanceof mb.Raw) return 'ord'
  return n.cls
}

const DRAWABLE = new Set(Array.from('()[]{}|‖⟨⟩⌊⌋⌈⌉/'))

// Lays out a row at a base pixel size.
export class Layout {
  base: number
  display: boolean
  constructor(base = 32.0, display = true) {
    this.base = base
    this.display = display
  }

  // ---------------------------------------------------------- basics
  layout(row: mb.Row): Box {
    return this.row(row, new St(this.base, this.display ? 0 : 1))
  }

  glyph(text: string, st: St, _kind = 'rm', scale = 1.0): Box {
    const px = fontPixelSize(st.em * scale)
    const [adv, a, d, right] = glyphMetrics(px, text)
    const b = new Box(adv, a, d)
    b.inkR = right
    b.ops.push({ k: 't', dx: 0, dy: 0, px, text })
    b.em = st.em
    b.charlike = true
    return b
  }

  phBox(st: St, ref: PhRef): Box {
    const em = st.em
    const b = new Box(0.56 * em, 0.66 * em, 0.08 * em)
    b.ops.push({ k: 'ph', dx: 0.03 * em, dy: -0.66 * em, w: 0.5 * em, h: 0.74 * em, ref })
    b.em = em
    return b
  }

  // ------------------------------------------------------------ rows
  row(row: mb.Row, st: St, lead: string | null = null): Box {
    const em = st.em
    if (!row.children.length) {
      const b = this.phBox(st, row)
      b.row = row
      b.gaps = [b.w / 2]
      return b
    }
    const boxes: Box[] = []
    let prevBox: Box | null = null
    for (const n of row.children) {
      const bx: Box = n instanceof mb.Scripts ? this.scripts(n, st, prevBox) : this.node(n, st)
      bx.node = n
      boxes.push(bx)
      prevBox = bx
    }
    // TeX spacing between math classes; a binary operator with nothing to
    // bind on its left (or right) acts as an ordinary.
    const kids = row.children
    const nK = kids.length
    const lefts = kids.map(leftCls)
    const b = new Box()
    b.row = row
    b.em = em
    let x = 0.0
    const gaps = [0.0]
    let prevR = lead
    boxes.forEach((bx, i) => {
      const k = kids[i]!
      let cur: string | null = lefts[i] ?? null
      if (cur === 'bin') {
        let nxt: string | null = null
        for (let j = i + 1; j < nK; j++) {
          if (lefts[j] !== null) { nxt = lefts[j]!; break }
        }
        if (prevR === null || ['bin', 'op', 'rel', 'open', 'punct'].includes(prevR)
          || nxt === null || ['rel', 'close', 'punct'].includes(nxt)) cur = 'ord'
      }
      let sp = 0.0
      if (cur !== null && prevR !== null) {
        const key = prevR + ' ' + cur
        let mu = SP[key] ?? 0
        if (st.level >= 2 && !SP_SCRIPT.has(key)) mu = 0
        sp = mu * em / 18.0
      }
      if (i > 0) gaps.push(x + sp / 2)
      x += sp
      b.add(x, 0.0, bx)
      x += bx.w
      b.asc = Math.max(b.asc, bx.asc)
      b.desc = Math.max(b.desc, bx.desc)
      if (k instanceof mb.Space) prevR = null
      else if (!(k instanceof mb.Scripts)) {
        prevR = (cur === 'ord' || cur === 'bin') && lefts[i] === 'bin' ? cur : rightCls(k)
      }
    })
    gaps.push(x)
    b.gaps = gaps
    b.w = x
    return b
  }

  // ----------------------------------------------------------- nodes
  node(n: mb.Node, st: St): Box {
    const em = st.em
    if (n instanceof mb.Atom) return this.atom(n, st)
    if (n instanceof mb.Symbol) {
      const g = n.glyph
      let italic = mb.GREEK_LOWER_GLYPHS.has(g) || g === '∂'
      if (['{', '}', '|', '%', '#', '&', '$', '_'].includes(n.cmd)) italic = false
      const v = st.variant !== null && ['bb', 'cal', 'frak', 'sf', 'tt'].includes(st.variant) ? 'rm' : st.variant
      const [t, kind] = mb.pyLen(g) === 1 ? styledChar(g, v, italic) : [g, 'rm']
      const b = this.glyph(t, st, kind)
      b.italic = italic
      return b
    }
    if (n instanceof mb.Func) return this.word(n.name, st)
    if (n instanceof mb.Placeholder) return this.phBox(st, n)
    if (n instanceof mb.Space) return new Box(n.mu * em / 18.0, 0, 0)
    if (n instanceof mb.Raw) return this.chip(n.latex, st, 'raw')
    if (n instanceof mb.CmdInput) return this.chip('\\' + n.text, st, 'cmd')
    if (n instanceof mb.Frac) return this.frac(n, st)
    if (n instanceof mb.Sqrt) return this.sqrt(n, st)
    if (n instanceof mb.BigOp) return this.bigop(n, st)
    if (n instanceof mb.Delim) {
      const body = this.row(n.body, st)
      return this.wrapDelims(body, mb.DELIMS[n.left] ?? n.left, mb.DELIMS[n.right] ?? n.right, st)
    }
    if (n instanceof mb.Matrix) return this.matrix(n, st)
    if (n instanceof mb.Accent) return this.accent(n, st)
    if (n instanceof mb.Styled) return this.row(n.body, st.withVariant(STYLE_VARIANT[n.cmd] ?? 'rm'))
    if (n instanceof mb.Text) return this.row(n.body, st.withVariant('text'))
    if (n instanceof mb.Group) return this.row(n.body, st)
    if (n instanceof mb.Scripts) return this.scripts(n, st, null)
    return this.chip('?', st, 'raw')
  }

  atom(n: mb.Atom, st: St): Box {
    let ch = n.char
    if (n.kind === 'text' || st.variant === 'text') {
      if (ch === ' ') return new Box(0.333 * st.em, 0, 0)
      return this.glyph(ch, st, 'rm')
    }
    if (ch === '′' || ch === "'") {
      const sub = st.sup()
      const g = this.glyph('′', sub)
      const b = new Box(g.w + 0.02 * st.em, g.asc + 0.38 * st.em, 0)
      b.add(0.0, -0.38 * st.em, g)
      return b
    }
    ch = ATOM_GLYPH[ch] ?? ch
    const italic = isAsciiAlpha1(ch)
    const [t, kind] = styledChar(ch, st.variant, italic)
    const b = this.glyph(t, st, kind)
    b.italic = italic && (st.variant === null || st.variant === 'it' || st.variant === 'bi')
    return b
  }

  word(text: string, st: St): Box {
    const b = this.glyph(text, st, 'rm')
    b.charlike = true
    return b
  }

  chip(text: string, st: St, kind: 'raw' | 'cmd'): Box {
    const em = st.em
    const px = fontPixelSize(0.5 * em)
    const w = monoAdvance(px, text) + 0.36 * em
    const b = new Box(w + 0.08 * em, 0.68 * em, 0.2 * em)
    b.ops.push({ k: 'chip', dx: 0.04 * em, dy: -0.68 * em, w, h: 0.88 * em, text, px, kind })
    return b
  }

  // -------------------------------------------------------- fraction
  frac(n: mb.Frac, st: St): Box {
    const em = st.em
    let inner: St
    let outerDisp: boolean
    if (['dfrac', 'cfrac', 'dbinom'].includes(n.cmd)) {
      inner = new St(st.base, 1, st.variant)
      outerDisp = true
    } else if (['tfrac', 'tbinom'].includes(n.cmd)) {
      inner = new St(st.base, 2, st.variant)
      outerDisp = false
    } else {
      inner = st.frac()
      outerDisp = st.level === 0
    }
    const num = this.row(n.num, inner)
    const den = this.row(n.den, inner)
    const t = Math.max(1.0, 0.04 * em)
    const axis = 0.25 * em
    const binom = n.cmd.includes('binom')
    const clr = !binom ? (outerDisp ? 3 * t : t) : (outerDisp ? 7 * t : 3 * t)
    let u = Math.max(outerDisp ? 0.677 * em : 0.394 * em, axis + t / 2 + clr + num.desc)
    let v = Math.max(outerDisp ? 0.686 * em : 0.345 * em, den.asc + clr + t / 2 - axis)
    if (binom) {
      u = Math.max(u, axis + clr / 2 + num.desc)
      v = Math.max(v, den.asc + clr / 2 - axis)
    }
    const m = 0.08 * em
    const innerW = Math.max(num.w, den.w) + 0.16 * em
    const b = new Box(innerW + 2 * m, u + num.asc, v + den.desc)
    b.add(m + (innerW - num.w) / 2, -u, num)
    b.add(m + (innerW - den.w) / 2, v, den)
    if (!binom) {
      b.ops.push({ k: 'rule', dx: m, dy: -axis - t / 2, w: innerW, h: t })
      return b
    }
    return this.wrapDelims(b, '(', ')', st)
  }

  // ------------------------------------------------------------ root
  sqrt(n: mb.Sqrt, st: St): Box {
    const em = st.em
    const body = this.row(n.body, st)
    const t = Math.max(1.0, 0.045 * em)
    const gap = t + (st.level === 0 ? 0.18 * em : 0.1 * em)
    const top = -(Math.max(body.asc, 0.62 * em) + gap + t)
    const bot = Math.max(body.desc, 0.05 * em) + 0.08 * em
    const H = bot - top
    const sw = Math.min(0.52 * em + 0.08 * H, 1.0 * em)
    let ix = 0.0
    let idxBox: Box | null = null
    if (n.index !== null) {
      idxBox = this.row(n.index, new St(st.base, 3, st.variant))
      ix = Math.max(0.0, idxBox.w - 0.5 * sw)
    }
    const b = new Box()
    const x0 = ix
    const mid = bot - Math.min(0.55 * em, H * 0.46)
    const p = new Path()
    p.moveTo(x0 + 0.02 * em, mid + 0.06 * em)
    p.lineTo(x0 + 0.16 * sw, mid - 0.02 * em)
    p.lineTo(x0 + 0.45 * sw, bot)
    p.lineTo(x0 + sw, top + t / 2)
    p.lineTo(x0 + sw + body.w + 0.1 * em, top + t / 2)
    b.ops.push({ k: 'stroke', path: p, width: t })
    const thick = new Path()
    thick.moveTo(x0 + 0.16 * sw, mid - 0.02 * em)
    thick.lineTo(x0 + 0.45 * sw, bot)
    b.ops.push({ k: 'stroke', path: thick, width: 2.3 * t })
    b.add(x0 + sw + 0.04 * em, 0.0, body)
    b.w = x0 + sw + body.w + 0.14 * em
    b.asc = -top
    b.desc = bot
    if (idxBox !== null) {
      const iy = mid - 0.12 * em - idxBox.desc
      b.add(Math.max(0.0, x0 + 0.5 * sw - idxBox.w), iy, idxBox)
      b.asc = Math.max(b.asc, -iy + idxBox.asc)
    }
    return b
  }

  // --------------------------------------------------------- scripts
  scripts(n: mb.Scripts, st: St, base: Box | null): Box {
    const em = st.em
    const sst = st.sup()
    const sup = n.sup !== null ? this.row(n.sup, sst) : null
    const sub = n.sub !== null ? this.row(n.sub, sst) : null
    const char = base === null || base.charlike
    const bAsc = base !== null ? base.asc : 0.45 * em
    const bDesc = base !== null ? base.desc : 0.0
    const t = Math.max(1.0, 0.04 * em)
    let u = 0.0
    let v = 0.0
    if (sup !== null) {
      u = Math.max(st.level === 0 ? 0.413 * em : 0.363 * em, sup.desc + 0.25 * 0.43 * em)
      if (!char) u = Math.max(u, bAsc - 0.25 * em)
    }
    if (sub !== null) {
      v = Math.max(0.15 * em, sub.asc - 0.8 * 0.43 * em)
      if (!char) v = Math.max(v, bDesc + 0.05 * em)
    }
    if (sup !== null && sub !== null) {
      v = Math.max(v, 0.247 * em)
      const clash = (u - sup.desc) - (sub.asc - v)
      if (clash < 4 * t) v += 4 * t - clash
    }
    // Tuck scripts against the ink of a single glyph rather than its
    // advance, which in the math italics carries generous bearings.
    let ic = 0.0
    let subX = 0.0
    if (base !== null && base.inkR !== null) {
      ic = Math.min(0.0, base.inkR - base.w) + (base.italic ? 0.04 * em : 0.02 * em)
      subX = Math.min(0.0, base.inkR - base.w) * 0.6
    }
    const b = new Box()
    let w = 0.0
    if (sup !== null) {
      b.add(ic, -u, sup)
      w = Math.max(w, ic + sup.w)
      b.asc = Math.max(b.asc, u + sup.asc)
      b.desc = Math.max(b.desc, sup.desc - u)
    }
    if (sub !== null) {
      b.add(subX, v, sub)
      w = Math.max(w, subX + sub.w)
      b.desc = Math.max(b.desc, v + sub.desc)
      b.asc = Math.max(b.asc, sub.asc - v)
    }
    b.w = w + 0.05 * em
    return b
  }

  // ------------------------------------------------------ big operator
  bigop(n: mb.BigOp, st: St): Box {
    const em = st.em
    const glyph = mb.BIGOPS[n.op] ?? ''
    const integral = mb.INTEGRALS.has(n.op)
    const disp = st.level === 0
    const sst = st.sup()
    const up = n.upper !== null ? this.row(n.upper, sst) : null
    const lo = n.lower !== null ? this.row(n.lower, sst) : null
    const axis = 0.25 * em
    let op: Box
    if (glyph) {
      const scale = disp ? (integral ? 2.0 : 1.42) : (integral ? 1.28 : 1.06)
      const g = this.glyph(glyph, st, 'rm', scale)
      // centre the operator on the math axis
      const shift = (g.asc - g.desc) / 2 - axis
      op = new Box(g.w, g.asc - shift, g.desc + shift)
      op.add(0.0, shift, g)
    } else {
      const label = ({ lim: 'lim', liminf: 'lim inf', limsup: 'lim sup' } as Record<string, string>)[n.op]!
      op = this.word(label, st)
    }
    const limits = disp && !integral
    const b = new Box()
    if (limits || (!glyph && disp)) {
      const w = Math.max(op.w, up ? up.w : 0, lo ? lo.w : 0)
      const ox = (w - op.w) / 2
      b.add(ox, 0.0, op)
      b.asc = op.asc
      b.desc = op.desc
      if (up !== null) {
        const y = -op.asc - 0.14 * em - up.desc
        b.add((w - up.w) / 2, y, up)
        b.asc = -y + up.asc
      }
      if (lo !== null) {
        const y = op.desc + 0.14 * em + lo.asc
        b.add((w - lo.w) / 2, y, lo)
        b.desc = y + lo.desc
      }
      b.w = w
      return b
    }
    b.add(0.0, 0.0, op)
    b.asc = op.asc
    b.desc = op.desc
    let w = op.w
    if (integral && glyph) {
      const kern = 0.3 * em * (disp ? 2.0 : 1.1)
      if (up !== null) {
        const y = -op.asc + up.asc * 0.95
        b.add(op.w, y, up)
        w = Math.max(w, op.w + up.w)
        b.asc = Math.max(b.asc, -y + up.asc)
      }
      if (lo !== null) {
        const y = op.desc - lo.desc * 0.4
        const x = Math.max(0.0, op.w - kern)
        b.add(x, y, lo)
        w = Math.max(w, x + lo.w)
        b.desc = Math.max(b.desc, y + lo.desc)
      }
      b.w = w + 0.08 * em
      return b
    }
    const sc = new mb.Scripts(n.lower, n.upper)
    const s = this.scripts(sc, st, op)
    b.add(op.w, 0.0, s)
    b.asc = Math.max(b.asc, s.asc)
    b.desc = Math.max(b.desc, s.desc)
    b.w = op.w + s.w
    return b
  }

  // --------------------------------------------------------- delimiters
  wrapDelims(body: Box, left: string, right: string, st: St): Box {
    const em = st.em
    const axis = 0.25 * em
    const delta = Math.max(body.asc - axis, body.desc + axis)
    const H = Math.max(2 * delta * 0.901, 2 * delta - 0.5 * em)
    const b = new Box()
    let x = 0.0
    const lb = this.delim(left, H, st)
    const rb = this.delim(right, H, st)
    b.add(x, 0.0, lb)
    x += lb.w
    b.add(x, 0.0, body)
    x += body.w
    b.add(x, 0.0, rb)
    b.w = x + rb.w
    b.asc = Math.max(lb.asc, rb.asc, body.asc)
    b.desc = Math.max(lb.desc, rb.desc, body.desc)
    return b
  }

  delim(ch: string, H: number, st: St): Box {
    const em = st.em
    if (!ch) return new Box(0.1 * em, 0, 0)
    const g = this.glyph(ch, st, 'rm')
    const natural = g.asc + g.desc
    if (H <= natural * 1.08 || !DRAWABLE.has(ch)) return g
    const axis = 0.25 * em
    const h = H / 2
    return drawDelim(ch, -axis - h, -axis + h, em)
  }

  // ---------------------------------------------------------- matrix
  matrix(n: mb.Matrix, st: St): Box {
    const em = st.em
    const env = n.env.replace(/\*+$/, '')
    const displayEnv = ['align', 'gather', 'equation', 'multline', 'aligned', 'gathered', 'split'].includes(env)
    let cst = new St(st.base, displayEnv ? 0 : Math.max(st.level, 1), st.variant)
    if (env === 'smallmatrix') cst = new St(st.base, 2, st.variant)
    // In align-like environments the right-hand column continues the left
    // one ("x &= 1"), so its leading relation keeps its spacing.
    const alignLike = env === 'align' || env === 'aligned' || env === 'split'
    const grid = n.rows.map(r => r.map((c, j) => this.row(c, cst, alignLike && j % 2 ? 'ord' : null)))
    const ncol = Math.max(0, ...grid.map(r => r.length))
    const colw = Array.from({ length: ncol }, () => 0)
    for (const r of grid) r.forEach((c, j) => { colw[j] = Math.max(colw[j]!, c.w) })
    let aligns: string[]
    let gaps: number[]
    const ng = Math.max(0, ncol - 1)
    if (alignLike) {
      aligns = Array.from({ length: ncol }, (_, j) => (j % 2 === 0 ? 'r' : 'l'))
      gaps = Array.from({ length: ng }, (_, j) => (j % 2 === 0 ? 0.0 : 1.6 * em))
    } else if (env === 'cases') {
      aligns = Array.from({ length: ncol }, () => 'l')
      gaps = Array.from({ length: ng }, () => 1.0 * em)
    } else {
      aligns = Array.from({ length: ncol }, () => 'c')
      gaps = Array.from({ length: ng }, () => (env === 'smallmatrix' ? 0.6 : 1.0) * em)
    }
    const jot = displayEnv ? 0.3 * em : 0.0
    const rowsGeo: number[] = []
    let y = 0.0
    const minA = 0.72 * cst.em
    const minD = 0.3 * cst.em
    grid.forEach((r, i) => {
      const a = Math.max(minA, ...r.map(c => c.asc))
      const d = Math.max(minD, ...r.map(c => c.desc))
      if (i) y += jot + a
      else y = a
      rowsGeo.push(y)
      y += d
    })
    const total = y
    const inner = new Box()
    grid.forEach((r, i) => {
      let x = 0.0
      for (let j = 0; j < ncol; j++) {
        const c = j < r.length ? r[j]! : null
        if (c !== null) {
          const al = aligns[j]
          const off = al === 'l' ? 0.0 : al === 'r' ? colw[j]! - c.w : (colw[j]! - c.w) / 2
          inner.add(x + off, rowsGeo[i]!, c)
        }
        x += colw[j]! + (j < ncol - 1 ? gaps[j]! : 0.0)
      }
    })
    inner.w = colw.reduce((s, v) => s + v, 0) + gaps.reduce((s, v) => s + v, 0)
    const axis = 0.25 * em
    const shift = -axis - total / 2
    const body = new Box(inner.w + 0.2 * em, -shift, total + shift)
    body.add(0.1 * em, shift, inner)
    const pairs: Record<string, [string, string]> = {
      pmatrix: ['(', ')'], bmatrix: ['[', ']'],
      Bmatrix: ['{', '}'], vmatrix: ['|', '|'],
      Vmatrix: ['‖', '‖'], cases: ['{', ''],
    }
    const pr = Object.prototype.hasOwnProperty.call(pairs, env) ? pairs[env] : undefined
    if (pr) return this.wrapDelims(body, pr[0], pr[1], st)
    return body
  }

  // ---------------------------------------------------------- accents
  accent(n: mb.Accent, st: St): Box {
    const em = st.em
    const body = this.row(n.body, st)
    const single = n.body.children.length === 1 && body.kids.length > 0 && body.kids[0]![2].italic
    const skew = single ? 0.08 * em : 0.0
    const t = Math.max(1.0, 0.045 * em)
    const top = -Math.max(body.asc, 0.45 * em) - 0.1 * em
    const cx = body.w / 2 + skew
    const cmd = n.cmd
    const b = new Box(body.w, 0, body.desc)
    b.add(0.0, 0.0, body)
    const wide = ['widehat', 'widetilde', 'overline', 'overrightarrow', 'underline'].includes(cmd)
    const aw = wide ? body.w : Math.min(Math.max(0.32 * em, body.w * 0.55), 0.5 * em)
    const x0 = (body.w - aw) / 2 + (!wide ? skew : 0.0)
    const accH = 0.18 * em
    const p = new Path()
    let kind: 'stroke' | 'fill' = 'stroke'
    if (cmd === 'hat' || cmd === 'widehat' || cmd === 'check') {
      const h = accH * (cmd !== 'widehat' ? 1.0 : 1.2)
      if (cmd === 'check') {
        p.moveTo(x0, top - h)
        p.lineTo(x0 + aw / 2, top)
        p.lineTo(x0 + aw, top - h)
      } else {
        p.moveTo(x0, top)
        p.lineTo(x0 + aw / 2, top - h)
        p.lineTo(x0 + aw, top)
      }
      b.asc = -top + h + t
    } else if (cmd === 'bar' || cmd === 'overline') {
      if (cmd === 'bar') {
        p.moveTo(x0, top - 0.05 * em)
        p.lineTo(x0 + aw, top - 0.05 * em)
      } else {
        p.moveTo(0.0, top)
        p.lineTo(body.w, top)
      }
      b.asc = -top + 0.05 * em + t
    } else if (cmd === 'underline') {
      const y = body.desc + 0.1 * em
      p.moveTo(0.0, y)
      p.lineTo(body.w, y)
      b.asc = body.asc
      b.desc = y + t
    } else if (cmd === 'vec' || cmd === 'overrightarrow') {
      const y = top - 0.08 * em
      const w = cmd === 'vec' ? aw : body.w
      const xs = cmd === 'vec' ? x0 : 0.0
      p.moveTo(xs, y)
      p.lineTo(xs + w, y)
      p.moveTo(xs + w - 0.12 * em, y - 0.08 * em)
      p.lineTo(xs + w, y)
      p.lineTo(xs + w - 0.12 * em, y + 0.08 * em)
      b.asc = -y + 0.09 * em + t
    } else if (cmd === 'tilde' || cmd === 'widetilde') {
      const y = top - 0.07 * em
      const h = 0.06 * em
      p.moveTo(x0, y + h)
      p.cubicTo(x0 + aw * 0.3, y - 2 * h, x0 + aw * 0.7, y + 2 * h, x0 + aw, y - h)
      b.asc = -y + 2 * h + t
    } else if (cmd === 'dot' || cmd === 'ddot' || cmd === 'mathring') {
      const r = 0.05 * em
      const y = top - 0.07 * em
      kind = 'fill'
      if (cmd === 'dot') p.addEllipse(cx, y, r, r)
      else if (cmd === 'ddot') {
        p.addEllipse(cx - 0.12 * em, y, r, r)
        p.addEllipse(cx + 0.12 * em, y, r, r)
      } else {
        kind = 'stroke'
        p.addEllipse(cx, y - 0.02 * em, 0.07 * em, 0.07 * em)
      }
      b.asc = -y + 0.1 * em
    } else if (cmd === 'acute' || cmd === 'grave') {
      const y = top
      if (cmd === 'acute') {
        p.moveTo(cx - 0.04 * em, y)
        p.lineTo(cx + 0.1 * em, y - 0.16 * em)
      } else {
        p.moveTo(cx + 0.04 * em, y)
        p.lineTo(cx - 0.1 * em, y - 0.16 * em)
      }
      b.asc = -y + 0.17 * em
    } else if (cmd === 'breve') {
      const y = top - 0.02 * em
      p.moveTo(x0, y - 0.14 * em)
      p.quadTo(cx, y + 0.06 * em, x0 + aw, y - 0.14 * em)
      b.asc = -y + 0.16 * em
    }
    b.ops.push({ k: kind, path: p, width: t })
    b.asc = Math.max(b.asc, body.asc)
    return b
  }
}

function drawDelim(ch: string, top: number, bot: number, em: number): Box {
  const H = bot - top
  const mid = (top + bot) / 2
  const b = new Box()
  b.asc = -top
  b.desc = bot
  const t = Math.max(1.0, 0.05 * em)
  const p = new Path()
  const side = 0.09 * em
  if (ch === '(' || ch === ')') {
    const w = Math.min(0.3 * em + 0.06 * H, 0.62 * em)
    const tm = 0.075 * em + 0.012 * H
    const te = 0.025 * em
    let xo = side
    let xi = side + w          // outer bulge x, end x
    const k = H * 0.02
    if (ch === '(') {
      const c = xi - (xi - xo) / 0.75
      p.moveTo(xi, top)
      p.cubicTo(c, top + H * 0.28 + k, c, bot - H * 0.28 - k, xi, bot)
      const c2 = xi - (xi - (xo + tm)) / 0.75
      p.lineTo(xi + te, bot - te)
      p.cubicTo(c2 + te, bot - H * 0.3, c2 + te, top + H * 0.3, xi + te, top + te)
      p.closeSubpath()
    } else {
      xo = side + w + te
      xi = side
      const c = xi + (xo - xi) / 0.75
      p.moveTo(xi + te, top)
      p.cubicTo(c + te, top + H * 0.28 + k, c + te, bot - H * 0.28 - k, xi + te, bot)
      const c2 = xi + ((xo - tm) - xi) / 0.75
      p.lineTo(xi, bot - te)
      p.cubicTo(c2, bot - H * 0.3, c2, top + H * 0.3, xi, top + te)
      p.closeSubpath()
    }
    b.ops.push({ k: 'fill', path: p, width: 0 })
    b.w = w + te + 2 * side
    return b
  }
  if ('[]⌊⌋⌈⌉'.includes(ch)) {
    const w = 0.3 * em
    const stem = 0.05 * em
    const bar = 0.04 * em
    const left = '[⌊⌈'.includes(ch)
    const x = left ? side : side + w - stem
    p.addRect(x, top, stem, H)
    const tops = '[]⌈⌉'.includes(ch)
    const bots = '[]⌊⌋'.includes(ch)
    const hx = side
    if (tops) p.addRect(hx, top, w, bar)
    if (bots) p.addRect(hx, bot - bar, w, bar)
    b.ops.push({ k: 'fill', path: p, width: 0 })
    b.w = w + 2 * side
    return b
  }
  if (ch === '{' || ch === '}') {
    const w = 0.42 * em
    const r = Math.min(0.2 * em, H / 5)
    const xm = side + w / 2
    let xl = side
    let xr = side + w
    if (ch === '}') [xl, xr] = [xr, xl]
    p.moveTo(xr, top)
    p.quadTo(xm, top, xm, top + r)
    p.lineTo(xm, mid - r)
    p.quadTo(xm, mid, xl, mid)
    p.quadTo(xm, mid, xm, mid + r)
    p.lineTo(xm, bot - r)
    p.quadTo(xm, bot, xr, bot)
    b.ops.push({ k: 'stroke', path: p, width: 0.06 * em })
    b.w = w + 2 * side
    return b
  }
  if (ch === '|' || ch === '‖') {
    const xs = ch === '|' ? [side + 0.03 * em] : [side + 0.03 * em, side + 0.17 * em]
    for (const x of xs) {
      p.moveTo(x, top)
      p.lineTo(x, bot)
    }
    b.ops.push({ k: 'stroke', path: p, width: 0.045 * em })
    b.w = xs[xs.length - 1]! + 0.03 * em + side
    return b
  }
  if (ch === '⟨' || ch === '⟩') {
    const w = Math.min(0.25 * em + 0.08 * H, 0.55 * em)
    if (ch === '⟨') {
      p.moveTo(side + w, top)
      p.lineTo(side, mid)
      p.lineTo(side + w, bot)
    } else {
      p.moveTo(side, top)
      p.lineTo(side + w, mid)
      p.lineTo(side, bot)
    }
    b.ops.push({ k: 'stroke', path: p, width: 0.045 * em })
    b.w = w + 2 * side
    return b
  }
  const w = 0.12 * H
  p.moveTo(side + w, top)
  p.lineTo(side, bot)
  b.ops.push({ k: 'stroke', path: p, width: t })
  b.w = w + 2 * side
  return b
}

// ------------------------------------------------------------ geometry

export class RowGeom {
  w: number
  asc: number
  desc: number
  gaps: number[]
  em: number
  row: mb.Row
  x: number
  y: number
  constructor(row: mb.Row, x: number, y: number, box: Box) {
    this.row = row
    this.x = x
    this.y = y
    this.w = box.w
    this.asc = box.asc
    this.desc = box.desc
    this.gaps = box.gaps.map(g => x + g)
    this.em = box.em
  }

  caretSpan(): [number, number] {
    return [this.y - Math.max(this.asc, 0.72 * this.em), this.y + Math.max(this.desc, 0.22 * this.em)]
  }

  // [x, y, w, h]
  rect(): [number, number, number, number] {
    const [a, d] = this.caretSpan()
    return [this.x, a, Math.max(this.w, 1.0), d - a]
  }
}

// row -> RowGeom for every row box, in absolute coordinates.
export function collectRows(box: Box, x = 0.0, y = 0.0, out = new Map<mb.Row, RowGeom>()): Map<mb.Row, RowGeom> {
  if (box.row !== null) out.set(box.row, new RowGeom(box.row, x, y, box))
  for (const [dx, dy, k] of box.kids) collectRows(k, x + dx, y + dy, out)
  return out
}

// node -> [x, y, w, h] of that node's box.
export function collectNodes(box: Box, x = 0.0, y = 0.0,
  out = new Map<mb.Node, [number, number, number, number]>()): Map<mb.Node, [number, number, number, number]> {
  if (box.node !== null) out.set(box.node, [x, y - box.asc, box.w, box.asc + box.desc])
  for (const [dx, dy, k] of box.kids) collectNodes(k, x + dx, y + dy, out)
  return out
}

// ------------------------------------------------------------ painting

export interface PaintCtx {
  active?: PhRef | null          // Row or Placeholder under the caret
  ink?: string
  showPlaceholders?: boolean
}

const esc = (s: string): string =>
  s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')

// SVG markup for box with its baseline origin at (x, y).
export function paint(box: Box, x: number, y: number, ctx: PaintCtx = {}): string {
  const out: string[] = []
  paintInto(out, box, x, y, {
    active: ctx.active ?? null, ink: ctx.ink ?? INK, showPlaceholders: ctx.showPlaceholders ?? true,
  })
  return out.join('')
}

function paintInto(out: string[], box: Box, x: number, y: number, ctx: Required<PaintCtx>): void {
  for (const op of box.ops) {
    if (op.k === 't') {
      out.push(`<text x="${n3(x + op.dx)}" y="${n3(y + op.dy)}" font-family="${MATH_FAMILY}" `
        + `font-size="${op.px}" fill="${ctx.ink}">${esc(op.text)}</text>`)
    } else if (op.k === 'rule') {
      out.push(`<rect x="${n3(x + op.dx)}" y="${n3(y + op.dy)}" width="${n3(op.w)}" height="${n3(op.h)}" fill="${ctx.ink}"/>`)
    } else if (op.k === 'stroke' || op.k === 'fill') {
      const d = op.path.svg(x, y)
      if (!d) continue
      if (op.k === 'fill') out.push(`<path d="${d}" fill="${ctx.ink}"/>`)
      else {
        out.push(`<path d="${d}" fill="none" stroke="${ctx.ink}" stroke-width="${n3(op.width)}" `
          + 'stroke-linecap="round" stroke-linejoin="round"/>')
      }
    } else if (op.k === 'ph') {
      if (!ctx.showPlaceholders) continue
      const active = op.ref === ctx.active
      const pw = Math.max(1.0, op.h / 30)
      const rx = n3(x + op.dx)
      const ry = n3(y + op.dy)
      if (active) out.push(`<rect x="${rx}" y="${ry}" width="${n3(op.w)}" height="${n3(op.h)}" fill="${PH_ACTIVE_FILL}"/>`)
      out.push(`<rect x="${rx}" y="${ry}" width="${n3(op.w)}" height="${n3(op.h)}" fill="none" `
        + `stroke="${active ? PH_ACTIVE : PH_PEN}" stroke-width="${n3(pw)}" stroke-dasharray="${n3(2 * pw)} ${n3(2 * pw)}"/>`)
    } else if (op.k === 'chip') {
      const cmd = op.kind === 'cmd'
      const r = n3(op.h * 0.18)
      out.push(`<rect x="${n3(x + op.dx)}" y="${n3(y + op.dy)}" width="${n3(op.w)}" height="${n3(op.h)}" rx="${r}" ry="${r}" `
        + `fill="${cmd ? '#fff6dc' : '#eef1f5'}" stroke="${cmd ? '#e2b54a' : '#c9d0da'}" stroke-width="1"/>`)
      out.push(`<text x="${n3(x + op.dx + op.w / 2)}" y="${n3(y + op.dy + op.h / 2)}" text-anchor="middle" `
        + `dominant-baseline="central" font-family='${MONO_FAMILY}' font-size="${op.px}" `
        + `fill="${cmd ? '#7a5300' : '#4a5566'}" xml:space="preserve">${esc(op.text)}</text>`)
    }
  }
  for (const [dx, dy, k] of box.kids) paintInto(out, k, x + dx, y + dy, ctx)
}

export interface RenderedImage {
  svg: string
  width: number
  height: number
  baseline: number
  box: Box
}

// render_image: row laid out tightly in an SVG of whole pixels
// (transparent background), baseline pad + ascent from the top.
export function renderRow(row: mb.Row, px = 20.0, display = false, pad = 4.0, ink = INK,
  showPlaceholders = true): RenderedImage {
  const box = new Layout(px, display).layout(row)
  const width = Math.max(1, Math.ceil(box.w + 2 * pad))
  const height = Math.max(1, Math.ceil(box.asc + box.desc + 2 * pad))
  const baseline = pad + box.asc
  const body = paint(box, pad, baseline, { ink, showPlaceholders })
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" `
    + `viewBox="0 0 ${width} ${height}" style="overflow:visible;white-space:pre">${body}</svg>`
  return { svg, width, height, baseline, box }
}

export function renderLatex(latex: string, px = 20.0, display = false, pad = 4.0): RenderedImage {
  return renderRow(mb.parseLatex(latex), px, display, pad)
}
