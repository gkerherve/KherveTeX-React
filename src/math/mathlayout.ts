const isAsciiAlpha1 = (ch: string): boolean => /^[A-Za-z]$/.test(ch)

// (text, font kind) for one character under a style variant. The math
// font is always present here, so this is mathlayout's unicode_math path.
export function styledChar(ch: string, variant: string | null, italicDefault: boolean): [string, string] {
  const v = variant
  if (v === null || v === 'it') {
    const wantIt = v === null ? italicDefault : mb.isAlphaStr(ch)
    if (!wantIt) return [ch, 'rm']
    if (isAsciiAlpha1(ch)) return [alpha(ch, ...VARIANTS.it!), 'rm']
    const cp = ch.codePointAt(0)!
    if (mb.pyLen(ch) === 1 && cp >= 0x3B1 && cp <= 0x3C9) return [fromCp(0x1D6FC + cp - 0x3B1), 'rm']
    if (Object.prototype.hasOwnProperty.call(GREEK_IT, ch)) return [fromCp(GREEK_IT[ch]!), 'rm']
    return [ch, 'rm']
  }
  if (v === 'rm' || v === 'text') return [ch, 'rm']
  const spec = VARIANTS[v]
  if (!spec) return [ch, 'rm']
  return [alpha(ch, ...spec), 'rm']
}

