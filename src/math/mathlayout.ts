export interface PathEl { t: 'M' | 'L' | 'C' | 'D'; x: number; y: number }

// QPainterPath's element list (curves as CurveTo + two CurveToData),
// with its quirks: an implicit MoveTo(0,0), a MoveTo replacing a
// MoveTo, zero-length segments dropped, quads lifted to cubics.
export class Path {
  els: PathEl[] = [{ t: 'M', x: 0, y: 0 }]
  closes = new Set<number>()
  private cStart = 0
  private requireMoveTo = false

  private last(): PathEl { return this.els[this.els.length - 1]! }

  private maybeMoveTo(): void {
    if (this.requireMoveTo) {
      const e = this.last()
      this.cStart = this.els.length
      this.els.push({ t: 'M', x: e.x, y: e.y })
      this.requireMoveTo = false
    }
  }

  moveTo(x: number, y: number): void {
    this.requireMoveTo = false
    const e = this.last()
    if (e.t === 'M') {
      e.x = x
      e.y = y
    } else {
      this.els.push({ t: 'M', x, y })
    }
    this.cStart = this.els.length - 1
  }

  lineTo(x: number, y: number): void {
    this.maybeMoveTo()
    const e = this.last()
    if (e.x === x && e.y === y) return
    this.els.push({ t: 'L', x, y })
  }

  cubicTo(c1x: number, c1y: number, c2x: number, c2y: number, x: number, y: number): void {
    this.maybeMoveTo()
    const e = this.last()
    if (e.x === c1x && e.y === c1y && c1x === c2x && c1y === c2y && c2x === x && c2y === y) return
    this.els.push({ t: 'C', x: c1x, y: c1y }, { t: 'D', x: c2x, y: c2y }, { t: 'D', x, y })
  }

  quadTo(cx: number, cy: number, x: number, y: number): void {
    this.maybeMoveTo()
    const p = this.last()
    if (p.x === cx && p.y === cy && cx === x && cy === y) return
    this.cubicTo((p.x + 2 * cx) / 3, (p.y + 2 * cy) / 3, (x + 2 * cx) / 3, (y + 2 * cy) / 3, x, y)
  }

  closeSubpath(): void {
    this.requireMoveTo = true
    const first = this.els[this.cStart]!
    const last = this.last()
    if (first.x !== last.x || first.y !== last.y) {
      if (Math.abs(first.x - last.x) < 1e-12 && Math.abs(first.y - last.y) < 1e-12) {
        last.x = first.x
        last.y = first.y
      } else {
        this.els.push({ t: 'L', x: first.x, y: first.y })
      }
    }
    this.closes.add(this.els.length - 1)
  }

  addRect(x: number, y: number, w: number, h: number): void {
    if (w === 0 && h === 0) return
    this.moveTo(x, y)
    this.els.push({ t: 'L', x: x + w, y }, { t: 'L', x: x + w, y: y + h },
      { t: 'L', x, y: y + h }, { t: 'L', x, y })
    this.closes.add(this.els.length - 1)
    this.requireMoveTo = true
  }

  addEllipse(cx: number, cy: number, rx: number, ry: number): void {
    const x = cx - rx
    const y = cy - ry
    const w = 2 * rx
    const h = 2 * ry
    if (w === 0 && h === 0) return
    const K = 0.5522847498
    const w2 = w / 2
    const h2 = h / 2
    const w2k = w2 * K
    const h2k = h2 * K
    this.moveTo(x + w, y + h2)
    this.cubicTo(x + w, y + h2 - h2k, x + w2 + w2k, y, x + w2, y)
    this.cubicTo(x + w2 - w2k, y, x, y + h2 - h2k, x, y + h2)
    this.cubicTo(x, y + h2 + h2k, x + w2 - w2k, y + h, x + w2, y + h)
    this.cubicTo(x + w2 + w2k, y + h, x + w, y + h2 + h2k, x + w, y + h2)
    this.closeSubpath()
    this.requireMoveTo = true
  }

  elementCount(): number { return this.els.length }

  controlPointRect(): [number, number, number, number] {
    let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity
    for (const e of this.els) {
      x0 = Math.min(x0, e.x); y0 = Math.min(y0, e.y)
      x1 = Math.max(x1, e.x); y1 = Math.max(y1, e.y)
    }
    return [x0, y0, x1 - x0, y1 - y0]
  }

  // SVG path data, translated by (ox, oy).
  svg(ox: number, oy: number): string {
    const out: string[] = []
    const els = this.els
    for (let i = 0; i < els.length; i++) {
      const e = els[i]!
      if (e.t === 'M') {
        // A trailing lone MoveTo draws nothing.
        if (i + 1 < els.length && els[i + 1]!.t !== 'M') out.push(`M${n3(e.x + ox)} ${n3(e.y + oy)}`)
      } else if (e.t === 'L') out.push(`L${n3(e.x + ox)} ${n3(e.y + oy)}`)
      else if (e.t === 'C') {
        const c2 = els[i + 1]!
        const p = els[i + 2]!
        out.push(`C${n3(e.x + ox)} ${n3(e.y + oy)} ${n3(c2.x + ox)} ${n3(c2.y + oy)} ${n3(p.x + ox)} ${n3(p.y + oy)}`)
        if (this.closes.has(i + 2)) out.push('Z')
        i += 2
        continue
      }
      if (this.closes.has(i)) out.push('Z')
    }
    return out.join('')
  }
}

export const n3 = (v: number): string => {
  const r = Math.round(v * 1000) / 1000
  return Object.is(r, -0) ? '0' : String(r)
}

