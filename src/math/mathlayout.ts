// Python's round(): halves go to the even neighbour.
export function pyRoundInt(x: number): number {
  const f = Math.floor(x)
  const d = x - f
  if (d > 0.5) return f + 1
  if (d < 0.5) return f
  return f % 2 === 0 ? f : f + 1
}

// QFont.setPixelSize(max(1, int(round(px)))) — the size Qt really uses.
export const fontPixelSize = (px: number): number => Math.max(1, pyRoundInt(px))

const q64 = (v: number): number => Math.floor(v * 64) / 64

type Measured = readonly number[]
const fallback = new Map<number, Measured>()

// The bit of the DOM the canvas fallback uses (this module also runs
// headless, where there is none).
interface DomLike {
  createElement(tag: 'canvas'): {
    getContext(kind: '2d'): {
      font: string
      measureText(t: string): {
        width: number; actualBoundingBoxLeft: number; actualBoundingBoxRight: number
        actualBoundingBoxAscent: number; actualBoundingBoxDescent: number
      }
    } | null
  }
}

// Metrics of a code point the math font lacks (Qt falls back to a system
// font). In a browser the canvas measures it; headless, a half-em guess.
function missingGlyph(cp: number): Measured {
  let m = fallback.get(cp)
  if (m) return m
  m = [UPM / 2, 0, 0, 0, 0]
  try {
    const doc = (globalThis as { document?: DomLike }).document
    if (doc) {
      const ctx = doc.createElement('canvas').getContext('2d')
      if (ctx) {
        ctx.font = `${UPM}px "${MATH_FAMILY}", serif`
        const t = ctx.measureText(String.fromCodePoint(cp))
        m = [t.width, -t.actualBoundingBoxLeft, -t.actualBoundingBoxDescent,
          t.actualBoundingBoxRight, t.actualBoundingBoxAscent]
      }
    }
  } catch { /* keep the guess */ }
  fallback.set(cp, m)
  return m
}

const metricCache = new Map<string, [number, number, number, number]>()

// (advance, ink ascent, ink descent, ink right edge) of text at an integer
// pixel size — QFontMetricsF.horizontalAdvance and tightBoundingRect.
export function glyphMetrics(px: number, text: string): [number, number, number, number] {
  const key = px + '\u0000' + text
  const hit = metricCache.get(key)
  if (hit) return hit
  const s = px / UPM
  let pen = 0
  let x1 = 0
  let y0 = Infinity
  let y1 = 0
  for (const ch of text) {
    const cp = ch.codePointAt(0)!
    const g = GLYPHS[cp] ?? missingGlyph(cp)
    const [adv, , gy0, gx1, gy1] = g.length > 1 ? g : [g[0]!, 0, 0, 0, 0]
    // Qt's tightBoundingBox: ink extents from the pen positions, with the
    // right and bottom edges starting from 0.
    x1 = Math.max(x1, pen + gx1! * s)
    y0 = Math.min(y0, -gy1! * s)
    y1 = Math.max(y1, -gy0! * s)
    pen += q64(adv! * s)
  }
  const m: [number, number, number, number] = text
    ? [pen, Math.max(0, -y0), Math.max(0, y1), x1]
    : [0, 0, 0, 0]
  metricCache.set(key, m)
  return m
}

export function monoAdvance(px: number, text: string): number {
  let w = 0
  for (const ch of text) { void ch; w += q64(MONO_ADVANCE * px) }
  return w
}

