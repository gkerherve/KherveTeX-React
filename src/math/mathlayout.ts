// TeX-like box layout and SVG rendering for mathbox trees — a port of
// khervedoc/mathlayout.py.
//
// Every node becomes a Box (width, ascent, descent, drawing ops and
// positioned child boxes). Row boxes remember the x position of each caret
// gap so the editor widget can hit-test clicks and draw the caret without
// knowing anything about the individual structures.
//
// Glyphs come from Latin Modern Math (the font unicode-math uses), with
// Unicode math-alphanumeric codepoints giving true math italics. Python
// measures them through Qt; here the font's own metrics (fontData.ts,
// generated by scripts/math_fonts.py) stand in, with advances floored to
// 1/64 px as Qt's 26.6 fixed point does.
import * as mb from './mathbox.ts'
import { GLYPHS, MATH_FAMILY, MONO_ADVANCE, UPM } from './fontData.ts'

