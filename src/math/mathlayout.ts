const fromCp = (cp: number): string => String.fromCodePoint(cp)

function alpha(ch: string, upper: number, lower: number,
  exc: Record<string, string> | null, digits: number | null): string {
  if (exc && Object.prototype.hasOwnProperty.call(exc, ch)) return exc[ch]!
  if (ch >= 'A' && ch <= 'Z' && ch.length === 1 && upper) return fromCp(upper + ch.charCodeAt(0) - 65)
  if (ch >= 'a' && ch <= 'z' && ch.length === 1 && lower) return fromCp(lower + ch.charCodeAt(0) - 97)
  if (ch >= '0' && ch <= '9' && ch.length === 1 && digits) return fromCp(digits + ch.charCodeAt(0) - 48)
  return ch
}

