// A short tip for a class with no entry (a user's own .cls).
export function classTip(cls: string, beta: boolean): Tip {
  const t = CLASS_INFO[cls] ?? T(cls, 'A document class.', 'Your own or an installed LaTeX class.')
  return beta ? { ...t, what: `${t.what} The page view of this class is in beta.` } : t
}
