def window_results(doc: Document, bundled: str, source_dir: Path | None,
                   root: Path) -> dict:
    from khervedoc import mainwindow
    from khervedoc.mainwindow import MainWindow
    real_box = mainwindow.QMessageBox
    mainwindow.QMessageBox = _Box
    try:
        _Box.log = []
        w = _FakeWindow(bundled, source_dir)
        w._editor.get_document = lambda: doc
        MainWindow._check_citations(w)
        check = _Box.log[-1]
    finally:
        mainwindow.QMessageBox = real_box
    w = _FakeWindow(bundled, source_dir)
    refreshed = MainWindow._refresh_kherveref_bib(w, doc)
    refresh = {"bib": refreshed, "bundled_bib": w._bundled_bib,
               "extra_bib": w._editor.extra}
    w = _FakeWindow(bundled, source_dir)
    stage_dir = root / "_stage"
    shutil.rmtree(stage_dir, ignore_errors=True)
    MainWindow._stage_kherveref_bib(w, doc, stage_dir / "a", stage_dir / "b" / "print")
    staged = None
    if (stage_dir / "a" / kr.BIB_FILE).exists():
        staged = [(stage_dir / "a" / kr.BIB_FILE).read_bytes().decode("utf-8"),
                  (stage_dir / "b" / "print" / kr.BIB_FILE).read_bytes().decode("utf-8")]
    shutil.rmtree(stage_dir, ignore_errors=True)
    return {"check": check, "refresh": refresh, "stage": staged,
            "stage_bundled_bib": w._bundled_bib}


def picker_results(current: str, bundled: str, browse_to: str | None,
                   selections: list) -> dict:
    from PySide6.QtCore import QItemSelectionModel
    from PySide6.QtWidgets import QApplication
    QApplication.instance() or QApplication([])
    from khervedoc import citation_picker
    real = citation_picker.QFileDialog.getExistingDirectory
    browsed: list = []

    def fake_dir(*_a, **_k):
        browsed.append(True)
        return browse_to or ""

    citation_picker.QFileDialog.getExistingDirectory = fake_dir
    try:
        dlg = citation_picker.CitationPicker(current, bundled, style="citet")
    finally:
        citation_picker.QFileDialog.getExistingDirectory = real
    combo = dlg._lib
    out = {
        "items": [[combo.itemText(i), combo.itemData(i)] for i in range(combo.count())],
        "index": combo.currentIndex(),
        "library": dlg.library,
        "browsed": bool(browsed),
        "empty": [dlg._empty.text(), not dlg._empty.isHidden()],
        "rows": {},
        "keys": [],
    }
    t = dlg._table
    for q in QUERIES:
        dlg._search.setText(q)
        out["rows"][q] = [[t.item(r, c).text() for c in range(4)]
                          for r in range(t.rowCount())]
    dlg._search.setText("")
    for rows, manual in selections:
        t.clearSelection()
        for r in rows:
            if r < t.rowCount():
                t.selectionModel().select(
                    t.model().index(r, 0),
                    QItemSelectionModel.Select | QItemSelectionModel.Rows)
        dlg._manual.setText(manual)
        out["keys"].append([rows, manual, dlg.keys()])
    t.clearSelection()
    dlg._manual.setText("")
    dlg.accept()
    out["accept_empty"] = [dlg.result(), dlg._empty.text(), not dlg._empty.isHidden()]
    out["style"] = dlg.style()
    dlg.deleteLater()
    return out


def b64(data: bytes) -> str:
    return base64.b64encode(data).decode("ascii")


