def pairs(d: dict) -> list:
    return [[k, v] for k, v in d.items()]


def safe(fn, *a, **k):
    try:
        return fn(*a, **k)
    except Exception as e:  # a crash is part of the behaviour to match
        return f"!ERROR {type(e).__name__}"


