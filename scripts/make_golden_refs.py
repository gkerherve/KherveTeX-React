def main() -> None:
    root_parent = Path(tempfile.mkdtemp(prefix="kherveref-golden-"))
    root = root_parent / "root"
    try:
        corpus = {
            "bibs": BIBS,
            "split_bib": {n: pairs(kr.split_bib(t)) for n, t in BIBS.items()},
            "string_definitions": {n: kr.string_definitions(t) for n, t in BIBS.items()},
            "parse_bibtex": {n: pairs(parse_bibtex(t)) for n, t in BIBS.items()},
            "search": {n: {q: kr.search(parse_bibtex(t), q) for q in QUERIES}
                       for n, t in BIBS.items()},
            "short_author": [[a, short_author(a)] for a in AUTHORS],
            "build_bib": [],
            "resolver": {},
            "fs": {},
        }
        all_src = [kr.split_bib(BIBS[n]) for n in ("duplicates", "kherveref_lib",
                                                   "macros_comments")]
        strings = [d for n in ("macros_comments", "kherveref_lib", "macros_comments")
                   for d in kr.string_definitions(BIBS[n])]
        for keys in (["dup", "smith2020surface", "real", "absent", "dup"], ["absent"], []):
            for st in ([], strings):
                text, missing = kr.build_bib(keys, all_src, st)
                corpus["build_bib"].append({"keys": keys, "strings": st,
                                            "sources": ["duplicates", "kherveref_lib",
                                                        "macros_comments"],
                                            "text": text, "missing": missing})
        base = root_parent / "resolver"
        (base / "sub").mkdir(parents=True)
        (base / "refs.bib").write_text(BIBS["references_test"], encoding="utf-8")
        (base / "sub" / "more.bib").write_text(
            "@misc{more1, author = {More, M.}, year = {2022}}\n", encoding="utf-8")
        for name, (doc, extra) in resolver_docs().items():
            corpus["resolver"][name] = {
                "with_base": resolver_case(doc, extra, base),
                "no_base": resolver_case(doc, extra, None),
            }
        corpus["resolver_files"] = {
            "refs.bib": BIBS["references_test"],
            "sub/more.bib": "@misc{more1, author = {More, M.}, year = {2022}}\n",
        }
        corpus["fs"] = fs_cases(root)
    finally:
        shutil.rmtree(root_parent, ignore_errors=True)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(corpus, indent=1, ensure_ascii=False) + "\n",
                   encoding="utf-8")
    print(f"wrote {OUT} ({len(corpus['fs'])} file-system cases, "
          f"{len(corpus['resolver'])} resolver documents)")


if __name__ == "__main__":
    main()
