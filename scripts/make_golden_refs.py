def resolver_case(doc: Document, extra: str, base: Path | None) -> dict:
    r = ReferenceResolver(doc, base, extra)
    keysets: list[list[str]] = []
    from khervedoc.references import _walk
    for n in _walk(doc):
        if isinstance(n, Citation) and n.keys not in keysets:
            keysets.append(list(n.keys))
    keysets += [["unknown"], [], ["a", "unknown"]]
    labels = list(r.labels) + ["missing", ""]
    return {
        "document_json": model.to_json(doc),
        "extra_bib": extra,
        "entries": pairs(r.entries),
        "cite_numbers": pairs(r.cite_numbers),
        "labels": pairs(r.labels),
        "cite": [[ks, st, r.cite_text(ks, st)] for ks in keysets
                 for st in ("cite", "citep", "citet", "other")],
        "ref": [[lb, kind, r.ref_text(lb, kind)] for lb in labels
                for kind in ("ref", "eqref", "pageref")],
    }


