"""Ship Latin Modern Math and its metrics to the TypeScript math layout.

mathlayout.py measures glyphs through Qt (QFontMetricsF.horizontalAdvance
and tightBoundingRect). The TS port cannot ask Qt, so this script reads the
same font with fontTools and writes, for every code point in its cmap, the
advance and ink bounds in font units to src/math/fontData.ts. The font file
itself is copied to public/fonts/math/ for the SVG @font-face (GUST Font
Licence: redistribution allowed).

    ../KherveTeX/.venv/bin/python scripts/math_fonts.py [path/to/latinmodern-math.otf]
"""
from __future__ import annotations

import shutil
import sys
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.ttLib import TTFont

HERE = Path(__file__).resolve().parent.parent
SRC = HERE.parent / "KherveTeX"


def find_font() -> Path:
    if len(sys.argv) > 1:
        return Path(sys.argv[1])
    roots = [SRC / "khervedoc" / "tectonic_cache",
             Path.home() / "Library/Caches/TectonicProject.Tectonic/bundles",
             Path.home() / "Library/Caches/Tectonic",
             Path.home() / ".cache/Tectonic"]
    for r in roots:
        hits = sorted(r.glob("**/latinmodern-math.otf")) if r.exists() else []
        if hits:
            return hits[0]
    raise SystemExit("latinmodern-math.otf not found; pass its path")


def _num(v: float) -> str:
    # CFF ink bounds include curve extrema, so they are not whole units.
    r = round(v, 3)
    return str(int(r)) if r == int(r) else repr(r)


def main() -> None:
    path = find_font()
    out_font = HERE / "public/fonts/math/latinmodern-math.otf"
    out_font.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(path, out_font)
    f = TTFont(str(path))
    upm = f["head"].unitsPerEm
    gs = f.getGlyphSet()
    hmtx = f["hmtx"]
    rows = []
    for cp, name in sorted(f.getBestCmap().items()):
        adv = hmtx[name][0]
        bp = BoundsPen(gs)
        gs[name].draw(bp)
        b = bp.bounds
        if b is None:
            rows.append(f"{cp}:[{adv}]")
        else:
            rows.append(f"{cp}:[{adv},{','.join(_num(v) for v in b)}]")
    lines = [
        "// Generated by scripts/math_fonts.py from latinmodern-math.otf — do not edit.",
        "// code point → [advance, xMin, yMin, xMax, yMax] in font units (y up);",
        "// a lone advance marks a glyph with no ink.",
        f"export const UPM = {upm}",
        "export const MATH_FAMILY = 'Latin Modern Math'",
        "// Menlo, the chip font: monospaced, 1233/2048 em per character.",
        "export const MONO_ADVANCE = 1233 / 2048",
        "export const GLYPHS: Record<number, readonly number[]> = {",
    ]
    for i in range(0, len(rows), 8):
        lines.append("  " + ", ".join(rows[i:i + 8]) + ",")
    lines.append("}")
    (HERE / "src/math/fontData.ts").write_text("\n".join(lines) + "\n")
    print(f"{len(rows)} glyphs from {path}")


if __name__ == "__main__":
    main()
