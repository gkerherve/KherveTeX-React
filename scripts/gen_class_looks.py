"""Write the visual editor's class look table and its fonts from ../KherveTeX.

- src/editor/classLooks.json: khervedoc/class_looks.py LOOKS (measured from
  real PDFs by packaging/measure_class_looks.py), never hand-written.
- public/fonts/: the Latin Modern design sizes and the other PDF fonts
  latex_fonts.pdf_font registers, copied from the tectonic cache.
- src/editor/fonts.css + src/editor/fontFiles.json: one @font-face family
  per design size ("KTeX LMRoman12"), as latex_fonts._register_design does,
  so a 17 pt title and a 12 pt body can share a page.

Run: python3 scripts/gen_class_looks.py  (uses ../KherveTeX/.venv if there)
"""
from __future__ import annotations

import json
import re
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
PY = HERE.parent / "KherveTeX"
sys.path.insert(0, str(PY))

from khervedoc.class_looks import LOOKS  # noqa: E402
from khervedoc import latex_fonts  # noqa: E402

out_json = HERE / "src" / "editor" / "classLooks.json"
out_json.write_text(json.dumps(LOOKS, ensure_ascii=False, separators=(",", ":")),
                    encoding="utf-8")

# The cache the installers ship, else the user's tectonic cache.
roots = [PY / "khervedoc" / "tectonic_cache", Path.home() / "Library/Caches/Tectonic",
         Path.home() / ".cache/Tectonic"]
font_dir = None
for root in roots:
    hits = sorted(root.glob("**/lmroman12-regular.otf"))
    if hits:
        font_dir = hits[0].parent
        break
if font_dir is None:
    sys.exit("no Latin Modern fonts in any tectonic cache")

public = HERE / "public" / "fonts"
public.mkdir(parents=True, exist_ok=True)
faces = []        # (family, weight, style, file)
families: dict[str, dict[str, bool]] = {}


def add(family: str, bold: bool, italic: bool, src: Path) -> None:
    shutil.copy2(src, public / src.name)
    faces.append((family, 700 if bold else 400, "italic" if italic else "normal", src.name))
    families.setdefault(family, {})["%d%d" % (bold, italic)] = True


design = re.compile(r"^(lmromancaps|lmromanslant|lmromandunh|lmroman|lmsans|lmmono)(\d+)-(\w+)\.otf$")
stems = {"lmromancaps": "LMRomanCaps", "lmromanslant": "LMRomanSlant",
         "lmromandunh": "LMRomanDunh", "lmroman": "LMRoman", "lmsans": "LMSans",
         "lmmono": "LMMono"}
for f in sorted(font_dir.iterdir()):
    m = design.match(f.name)
    if not m:
        continue
    stem, size, style = stems[m.group(1)], m.group(2), m.group(3)
    weights = {"regular": (0, 0), "bold": (1, 0), "italic": (0, 1), "oblique": (0, 1),
               "bolditalic": (1, 1), "boldoblique": (1, 1)}
    if style not in weights:
        continue
    b, i = weights[style]
    add(f"KTeX {stem}{size}", bool(b), bool(i), f)

for _prefix, family, files in latex_fonts._OTHER_FAMILIES:
    for (b, i), name in files.items():
        src = font_dir / name
        if src.exists() and not any(x[3] == name and x[0] == family for x in faces):
            add(family, bool(b), bool(i), src)

css = ["/* Generated by scripts/gen_class_looks.py — do not edit. */"]
for family, weight, style, name in faces:
    # The baseline sits where Qt puts it in a fixed-height line
    # (editor.BASELINE_AT of a 1.2 em line) and lines are as tall as Qt's
    # (Latin Modern's hhea ascent + descent, 1.407 em).
    css.append(
        "@font-face { font-family: '%s'; src: url('/fonts/%s'); font-weight: %d; "
        "font-style: %s; font-display: block; ascent-override: 105.15%%; "
        "descent-override: 35.55%%; line-gap-override: 0%%; }" % (family, name, weight, style))
(HERE / "src" / "editor" / "fonts.css").write_text("\n".join(css) + "\n", encoding="utf-8")
(HERE / "src" / "editor" / "fontFiles.json").write_text(
    json.dumps(families, indent=1, sort_keys=True) + "\n", encoding="utf-8")
print(f"{len(LOOKS)} classes, {len(faces)} font faces from {font_dir}")
