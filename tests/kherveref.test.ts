// Port of KherveTeX tests/test_kherveref.py: library reading, kherveref.bib,
// serializer, .ktex bundling, display and the citation picker's logic.
// Never touches the user's real KherveRef settings: every test installs a
// fake (or none) with setKherverefSettings, as the Python tests monkeypatch
// kherveref_link._settings.
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, statSync, unlinkSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { afterEach, beforeEach, describe, expect, it } from 'vitest'
import { loadKdocz, readBundledBib, saveKdocz } from '../src/core/kdocz.ts'
import * as kr from '../src/core/kherveref.ts'
import { citation, document, fromJson, paragraph, rawLatex, text, toJson } from '../src/core/model.ts'
import type { Citation, Document } from '../src/core/model.ts'
import { ReferenceResolver } from '../src/core/references.ts'
import { serializeDocument } from '../src/core/serializer.ts'
import { nodeFs } from './nodeFs.ts'

const nodeRefFs: kr.RefFileAccess = {
  ...nodeFs,
  listDir: async (d) => readdirSync(d),
  isFile: async (p) => {
    try { return statSync(p).isFile() } catch { return false }
  },
}

const LIB_BIB = String.raw`% generated by KherveRef
@string{jacs = "J. Am. Chem. Soc."}
@article{smith2020surface,
  author  = {Smith, Jane and M{\"{u}}ller, Anna},
  title   = {{XPS} of {TiO2} {surfaces}},
  journal = jacs,
  year    = {2020},
  pages   = {1--2}
}

@book(doe2019book, author = {Doe, John}, title = {A Book (2nd ed.)},
  publisher = {Pub}, year = {2019})
`

function _doc(keys: string[], style: Citation['style'] = 'citep', library = ''): Document {
  const d = document([paragraph([text('See '), ...keys.map((k) => citation([k], style))])])
  d.meta.ref_library = library
  return d
}

let tmpPath: string
let library: string

beforeEach(() => {
  tmpPath = mkdtempSync(join(tmpdir(), 'kherveref-'))
  library = join(tmpPath, 'MyLib')
  mkdirSync(library)
  writeFileSync(join(library, 'library.bib'), LIB_BIB, 'utf-8')
  writeFileSync(join(library, 'library.json'), JSON.stringify({ name: 'Thesis' }))
  kr.setKherverefSettings(null)
})

afterEach(() => kr.setKherverefSettings(null))

describe('kherveref', () => {
  it('test_split_bib', () => {
    const entries = kr.splitBib(LIB_BIB)
    expect([...entries.keys()]).toEqual(['smith2020surface', 'doe2019book'])
    expect(entries.get('smith2020surface')!.endsWith('pages   = {1--2}\n}')).toBe(true)
    expect(entries.get('doe2019book')!.endsWith('year = {2019})')).toBe(true)
  })

  it('test_cited_keys_in_first_citation_order', () => {
    expect(kr.citedKeys(_doc(['b', 'a', 'b']))).toEqual(['b', 'a'])
  })

  it('test_build_bib_order_and_missing', () => {
    const [t, missing] = kr.buildBib(['doe2019book', 'nope', 'smith2020surface'], [kr.splitBib(LIB_BIB)])
    expect(missing).toEqual(['nope'])
    expect(t.indexOf('doe2019book')).toBeLessThan(t.indexOf('smith2020surface'))
  })

  it('test_bibliography_from_library_then_bundle', async () => {
    const d = _doc(['smith2020surface'], 'citep', library)
    const [t, missing] = await kr.bibliographyFor(d, nodeRefFs)
    expect(t).toContain('@article{smith2020surface')
    expect(missing).toEqual([])
    expect(t).not.toContain('doe2019book')

    // Library gone (another PC): the copy carried by the .ktex is used.
    d.meta.ref_library = join(tmpPath, 'elsewhere')
    const [t2, missing2] = await kr.bibliographyFor(d, nodeRefFs, t)
    expect(t2).toContain('@article{smith2020surface')
    expect(missing2).toEqual([])

    // The live library wins over a stale bundle.
    const stale = t.replace('{2020}', '{1999}')
    d.meta.ref_library = library
    expect((await kr.bibliographyFor(d, nodeRefFs, stale))[0]).toContain('{2020}')
  })

  it('test_known_libraries', async () => {
    kr.setKherverefSettings(() => ({
      value: (key: string, def?: unknown) =>
        ({ recent_libraries: [library, '/nowhere'], last_library: library } as Record<string, unknown>)[key] ?? def,
    }))
    expect(await kr.knownLibraries(nodeRefFs)).toEqual([library])
    expect(await kr.libraryName(library, nodeRefFs)).toBe('Thesis')
    unlinkSync(join(library, 'library.json'))
    writeFileSync(join(library, 'My Thesis.kref'), JSON.stringify({ name: 'My Thesis' }))
    expect(await kr.libraryName(library, nodeRefFs)).toBe('My Thesis')
  })

  it('known_libraries is empty without settings', async () => {
    expect(await kr.knownLibraries(nodeRefFs)).toEqual([])
  })

  it('test_serializer_adds_bibliography_and_natbib', () => {
    const tex = serializeDocument(_doc(['smith2020surface'], 'citep', '/lib'))
    expect(tex).toContain('\\citep{smith2020surface}')
    expect(tex.trimEnd().endsWith('\\bibliographystyle{plainnat}\n\\bibliography{kherveref}\n\\end{document}')).toBe(true)
    expect(tex).toContain('\\usepackage{natbib}')
  })

  it('test_serializer_leaves_unmanaged_documents_alone', () => {
    const tex = serializeDocument(_doc(['x']))
    expect(tex).not.toContain('kherveref')
    expect(tex).not.toContain('natbib')
  })

  it('test_serializer_extends_existing_bibliography', () => {
    const d = _doc(['smith2020surface'], 'citep', '/lib')
    d.children.push(rawLatex('\\bibliographystyle{unsrt}\n\\bibliography{refs}'))
    const tex = serializeDocument(d)
    expect(tex).toContain('\\bibliography{refs,kherveref}')
    expect(tex.split('\\bibliography{').length - 1).toBe(1)
  })

  it('test_meta_round_trip', () => {
    const d = _doc(['a'], 'citep', '/some/lib')
    d.meta.bib_style = 'unsrtnat'
    const back = fromJson(toJson(d))
    expect([back.meta.ref_library, back.meta.bib_style]).toEqual(['/some/lib', 'unsrtnat'])
    expect(fromJson(toJson(document())).meta.bib_style).toBe('plainnat')
  })

  it('test_ktex_bundles_bib', async () => {
    const path = join(tmpPath, 'doc.ktex')
    await saveKdocz(_doc(['a'], 'citep', '/lib'), path, nodeFs, '@misc{a, title={A}}\n')
    expect(await readBundledBib(path, nodeFs)).toBe('@misc{a, title={A}}\n')
    const [, extract] = await loadKdocz(path, join(tmpPath, 'extract'), nodeFs)
    expect(statSync(join(extract, 'kherveref.bib')).isFile()).toBe(true)
    const plain = join(tmpPath, 'plain.ktex')
    await saveKdocz(_doc(['a']), plain, nodeFs)
    expect(await readBundledBib(plain, nodeFs)).toBe('')
  })

  it('test_resolver_uses_kherveref_entries', () => {
    const d = _doc(['smith2020surface'], 'citet')
    const r = new ReferenceResolver(d, null, LIB_BIB)
    const shown = r.citeText(['smith2020surface'], 'citet')
    expect(shown === 'Smith and Müller (2020)' || shown.startsWith('Smith')).toBe(true)
    expect(shown).not.toContain('?')
  })

  it('test_citation_picker', async () => {
    // known_libraries -> [library]
    kr.setKherverefSettings(() => ({ value: (key: string) => (key === 'last_library' ? library : []) }))
    const { items, index } = await kr.pickerLibraries('', '', nodeRefFs)
    const { entries, library: chosen } = await kr.pickerLoad(items[index].data, '', nodeFs)
    expect(chosen).toBe(library)
    expect(kr.pickerRows(entries, '').length).toBe(2)
    const rows = kr.pickerRows(entries, 'tio2')
    expect(rows.length).toBe(1)
    expect(kr.pickerKeys(rows, [0], 'other2001, smith2020surface')).toEqual(['smith2020surface', 'other2001'])
    expect(kr.STYLES.map(([c]) => c)).toContain('citet')
  })

  it('test_picker_offers_bundled_copy', async () => {
    const { items, index } = await kr.pickerLibraries('/gone', LIB_BIB, nodeRefFs)
    const { entries, library: chosen } = await kr.pickerLoad(items[index].data, LIB_BIB, nodeFs)
    expect(chosen).toBe('')
    expect(kr.pickerRows(entries, '').length).toBe(2)
  })

  // Needs tectonic, which the TypeScript core does not drive.
  it.skip('test_compiles_with_bibtex', () => {})

  it('test_string_macros_travel_with_entries', async () => {
    const d = _doc(['smith2020surface'], 'citep', library)
    const [t] = await kr.bibliographyFor(d, nodeRefFs)
    expect(t.indexOf('@string{jacs = "J. Am. Chem. Soc."}')).toBeLessThan(t.indexOf('@article{smith2020surface'))
    expect(t.indexOf('@string{jacs')).toBeGreaterThanOrEqual(0)
    expect((await kr.bibliographyFor(_doc(['nothing'], 'citep', library), nodeRefFs))[0]).toBe('')
  })

  // MainWindow's part, through the same core functions refs.ts calls:
  // cite, save the bundle, lose the library, reopen, stage.
  it('test_window_cites_saves_bundle_and_reopens', async () => {
    const doc = _doc(['smith2020surface'], 'citet', library)
    const r = await kr.refreshKherverefBib(doc, '', nodeRefFs)
    expect(kr.citedKeys(doc)).toEqual(['smith2020surface'])
    expect(new ReferenceResolver(doc, null, r.extraBib).citeText(['smith2020surface'], 'citet')).toContain('Smith')

    const path = join(tmpPath, 'paper.ktex')
    await saveKdocz(doc, path, nodeFs, r.bib)
    expect(await readBundledBib(path, nodeFs)).toContain('@article{smith2020surface')

    // On a PC without the library the bundled copy keeps it compiling.
    unlinkSync(join(library, 'library.bib'))
    const [reopened] = await loadKdocz(path, join(tmpPath, 'x'), nodeFs)
    const bundled = await readBundledBib(path, nodeFs)
    expect(bundled).toContain('@article{smith2020surface')
    const work = join(tmpPath, 'build')
    await kr.stageKherverefBib(reopened, bundled, [work], nodeRefFs)
    expect(readFileSync(join(work, kr.BIB_FILE), 'utf-8')).toContain('@article{smith2020surface')
  })

  it('check_citations reports missing keys', async () => {
    expect((await kr.checkCitations(_doc([]), '', null, nodeRefFs)).text).toBe('The document cites nothing.')
    const ok = await kr.checkCitations(_doc(['smith2020surface'], 'citep', library), '', null, nodeRefFs)
    expect(ok).toEqual({ kind: 'information', title: 'Citations', text: 'All 1 cited keys are defined.' })
    const bad = await kr.checkCitations(_doc(['smith2020surface', 'nope'], 'citep', library), '', null, nodeRefFs)
    expect(bad.kind).toBe('warning')
    expect(bad.text.startsWith('1 of 2 cited keys are not in Thesis:\n\nnope\n\n')).toBe(true)
  })
})
